"""Diagrams generated from the design, so they can't drift from it.

* Mermaid block diagram + memory map + register tables, from rvgrid/config.py.
  GitHub and VS Code render Mermaid inline in Markdown.
* Netlist schematics (SVG) of the real elaborated RTL: Yosys ``write_json``
  piped into netlistsvg (``npx netlistsvg``). Optional, needs both tools.

    python -m rvgrid diagram
"""

