DOCS = ROOT / "docs"
GENERATED = DOCS / "generated"
IMG = DOCS / "img"
README_BEGIN = "<!-- rvgrid:generated:begin -->"
README_END = "<!-- rvgrid:generated:end -->"


def hexaddr(v):
    return f"0x{v >> 16:04X}_{v & 0xFFFF:04X}"


def size_str(n):
    for unit, div in (("MiB", 1 << 20), ("KiB", 1 << 10)):
        if n >= div and n % div == 0:
            return f"{n // div} {unit}"
    return f"{n} B"


def mermaid_block(cfg: SoCConfig) -> str:
    t = {r.name: r for r in tile_regions(cfg)}
    s = system_regions(cfg)
    cpu_file, _, cpu_desc = VARIANTS[cfg.cpu]
    lines = [
        "flowchart LR",
        '    host(["host port<br/>(testbench / PCIe / NoC)"])',
        '    subgraph tile0["tile 0"]',
        "        direction LR",
        f'        cpu["{Path(cpu_file).stem}<br/>{cpu_desc}"]',
        '        fetch{{"fetch<br/>decoder"}}',
        '        arb{{"arbiter<br/>round-robin"}}',
        '        dec{{"tile<br/>decoder"}}',
        f'        l1[("L1 SRAM<br/>{size_str(t["L1"].size)}<br/>{hexaddr(t["L1"].base)}")]',
        f'        timer["TIMER<br/>{hexaddr(t["TIMER"].base)}"]',
        f'        ctrl["TILECTRL<br/>{hexaddr(t["TILECTRL"].base)}"]',
        "        cpu -- ibus --> fetch",
        "        fetch -- port A --> l1",
        "        cpu -- dbus --> arb",
        "        arb --> dec",
        "        dec -- port B --> l1",
        "        dec --> timer",
        "        dec --> ctrl",
        "        timer -. irq .-> cpu",
        "        ctrl -. hold .-> cpu",
        "    end",
        "    host --> arb",
        '    sys{{"system<br/>decoder"}}',
        f"    dec -- ext {hexaddr(SYSTEM_WINDOW.base)}+ --> sys",
    ]
    pins = {"UART": "uart_tx", "LEDS": "leds[7:0]", "SIMCTRL": "sim_done / sim_code"}
    for r in s:
        n = r.name.lower()
        lines.append(f'    {n}["{r.name}<br/>{hexaddr(r.base)}"]')
        lines.append(f"    sys --> {n}")
        lines.append(f'    {n} --> pin_{n}(["{pins[r.name]}"])')
    return "\n".join(lines)


def memory_map_table(cfg: SoCConfig) -> str:
    rows = ["| Region | Base | End | Size | Scope | What |", "|---|---|---|---|---|---|"]
    for r in all_regions(cfg):
        rows.append(f"| `{r.name}` | `{hexaddr(r.base)}` | `{hexaddr(r.end)}` | {size_str(r.size)} "
                    f"| {r.scope} | {r.desc} |")
    rows.append("| *(anything else)* | | | | | bus error: ERR, recorded in `TILECTRL.BUSERR_*` |")
    return "\n".join(rows)


def register_tables(cfg: SoCConfig) -> str:
    out = []
    for r in all_regions(cfg):
        regs = getattr(r.periph, "REGS", ())
        if not regs:
            continue
        out.append(f"### {r.name} @ `{hexaddr(r.base)}`\n")
        out.append("| Offset | Register | Access | Reset | Description |")
        out.append("|---|---|---|---|---|")
        for reg in regs:
            reset = reg.reset
            if r.periph is UART and reg.name == "DIVISOR":
                reset = cfg.divisor
            out.append(f"| `+0x{reg.offset:02X}` | `{r.name}_{reg.name}` | {reg.access} "
                       f"| `0x{reset:X}` | {reg.desc} |")
        out.append("")
    return "\n".join(out)


def generated_markdown(cfg: SoCConfig) -> str:
    return "\n".join([
        "# rvgrid: generated architecture reference",
        "",
        "> Generated by `python -m rvgrid diagram` from `rvgrid/config.py`. Do not edit.",
        "",
        "## Block diagram",
        "",
        "```mermaid",
        mermaid_block(cfg),
        "```",
        "",
        "## Memory map",
        "",
        memory_map_table(cfg),
        "",
        "## Registers",
        "",
        "All registers are 32-bit; use `lw`/`sw`. C macros with the same names are in "
        "`build/include/soc.h`.",
        "",
        register_tables(cfg),
    ])


def update_readme(cfg: SoCConfig):
    readme = ROOT / "README.md"
    text = readme.read_text()
    block = "\n".join([
        README_BEGIN,
        "```mermaid",
        mermaid_block(cfg),
        "```",
        "",
        memory_map_table(cfg),
        README_END,
    ])
    pattern = re.compile(re.escape(README_BEGIN) + ".*?" + re.escape(README_END), re.S)
    if pattern.search(text):
        new = pattern.sub(lambda _: block, text)
        if new != text:
            readme.write_text(new)
    return readme


# ---- Netlist schematics -------------------------------------------------------

def _yosys():
    return shutil.which("yosys")


def netlist_svg(elaboratable, name, out_svg, flatten=False, blackbox_cpu=True):
    """Elaborate -> RTLIL -> Yosys JSON -> netlistsvg SVG."""
    yosys = _yosys()
    npx = shutil.which("npx")
    if not yosys or not npx:
        return None
    work = BUILD / "diagram"
    work.mkdir(parents=True, exist_ok=True)
    il = work / f"{name}.il"
    js = work / f"{name}.json"
    il.write_text(rtlil.convert(elaboratable, name=name, emit_src=False))
    script = [f"read_rtlil {il}"]
    if blackbox_cpu:
        stub = work / "cpu_stub.v"
        stub.write_text(_cpu_stub())
        script.insert(0, f"read_verilog -lib {stub}")
    script += [f"hierarchy -top {name}", "proc", "opt_clean"]
    if flatten:
        script += ["flatten", "opt", "opt_clean"]
    script += [f"write_json {js}"]
    subprocess.run([yosys, "-q", "-p", "; ".join(script)], check=True)
    out_svg.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([npx, "--yes", "netlistsvg@1.0.2", str(js), "-o", str(out_svg)],
                   check=True, capture_output=True)
    return out_svg


def _cpu_stub():
    """Port-only VexRiscv so the schematic shows the core as one box."""
    ports = ["input clk", "input reset", "input [31:0] externalResetVector",
             "input timerInterrupt", "input softwareInterrupt",
             "input [31:0] externalInterruptArray"]
    for b in ("iBusWishbone", "dBusWishbone"):
        ports += [f"output {b}_CYC", f"output {b}_STB", f"output {b}_WE",
                  f"output [29:0] {b}_ADR", f"output [31:0] {b}_DAT_MOSI",
                  f"output [3:0] {b}_SEL", f"input [31:0] {b}_DAT_MISO",
                  f"input {b}_ACK", f"input {b}_ERR"]
    names = {Path(f).stem for f, _, _ in VARIANTS.values()}
    return "\n".join(f"(* blackbox *) module {n}({', '.join(p.split()[-1] for p in ports)});\n"
                     + "".join(f"  {p};\n" for p in ports) + "endmodule\n" for n in names)


# ---- Waveforms from the simulator ------------------------------------------

WAVES_VCD = BUILD / "sim" / "verilator-waves" / "runs" / "hello" / "dump.vcd"


def waveform_svgs(vcd=WAVES_VCD):
    """Two windows of the real ``hello`` run: boot, and the first console byte."""
    from .wave import Row, render_svg, sample

    cfg = SoCConfig()
    clk = "rvgrid_soc.clk"
    cpu = "rvgrid_soc.tile0.cpu."
    byte = lambda v: f"{v << 2:x}"      # noqa: E731  word address -> byte address
    word = lambda v: f"{v:08x}"         # noqa: E731
    out = []

    ib = cpu + "ibus__"
    rows = [Row("clk", clk, clock=True), Row("core hold", cpu + "hold"),
            Row("ibus.cyc/stb", ib + "cyc"), Row("ibus.adr", ib + "adr", fmt=byte, valid=ib + "cyc"),
            Row("ibus.ack", ib + "ack"), Row("ibus.dat_r", ib + "dat_r", fmt=lambda v: f"{v:x}", valid=ib + "ack")]
    sample(vcd, clk, rows, lambda p, v: p.endswith(".hold") and v == 0, 20)
    svg = IMG / "wave_boot.svg"
    svg.write_text(render_svg(rows, "Boot: the host clears HOLD and the core fetches _start "
                                    "from 0x0, one instruction every 2 cycles", cycle_w=34))
    out.append(svg)

    uart = next(r for r in system_regions(cfg) if r.name == "UART").base >> 2
    state = {}

    def first_uart_write(path, val):
        state[path] = val
        return (state.get(cpu + "dbus__cyc") and state.get(cpu + "dbus__we")
                and state.get(cpu + "dbus__adr") == uart)

    db = cpu + "dbus__"
    rows = [Row("clk", clk, clock=True), Row("dbus.cyc/stb", db + "cyc"),
            Row("dbus.we", db + "we"),
            Row("dbus.adr", db + "adr", fmt=byte, valid=db + "cyc"),
            Row("dbus.dat_w", db + "dat_w", fmt=word, valid=db + "cyc"),
            Row("dbus.ack", db + "ack"), Row("uart_tx", "rvgrid_soc.uart_tx")]
    sample(vcd, clk, rows, first_uart_write, 34)
    svg = IMG / "wave_uart.svg"
    svg.write_text(render_svg(rows, "First console byte: sw 'H' (0x48) to UART.TXDATA. uart_tx "
                                    "sends the start bit, then d0..d2 = 0; meanwhile the core "
                                    "loads the next format character from 0x71c", cycle_w=34))
    out.append(svg)
    return out


def write_all(netlist=True):
    cfg = SoCConfig()
    GENERATED.mkdir(parents=True, exist_ok=True)
    md = GENERATED / "architecture.md"
    md.write_text(generated_markdown(cfg))
    written = [md, update_readme(cfg)]
    if netlist:
        if not _yosys() or not shutil.which("npx"):
            print("skipping schematics: needs yosys (scripts/setup-tools.sh) and npx (Node.js)")
        else:
            jobs = [
                (SoC(cfg), "soc", IMG / "soc_netlist.svg", False),
                (Decoder([("l1", 0, cfg.l1_size), ("timer", 0x0200_0000, 0x1000)]),
                 "decoder", IMG / "decoder_netlist.svg", True),
            ]
            for design, name, svg, flat in jobs:
                if netlist_svg(design, name, svg, flatten=flat):
                    written.append(svg)
    if WAVES_VCD.exists():
        written += waveform_svgs()
    else:
        print("skipping waveform SVGs: run `python -m rvgrid sim hello --waves` first")
    return written
