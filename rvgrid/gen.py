"""Generators: Verilog for the simulators, C header + linker map for firmware.

    python -m rvgrid gen            # writes build/rtl/*.v and build/include/*
"""

from pathlib import Path

from amaranth.back import verilog

from .config import SoCConfig, all_regions
from .soc import SoC

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
TOP_NAME = "rvgrid_soc"


def generate_rtl(cfg: SoCConfig, out_dir=BUILD / "rtl", firmware: bytes | None = None,
                 name=TOP_NAME):
    """Write ``<name>.v`` plus the CPU sources. Returns all Verilog paths."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    soc = SoC(cfg, firmware=firmware)
    sources = soc.verilog_sources(out_dir)
    text = verilog.convert(soc, name=name, emit_src=False)
    top = out_dir / f"{name}.v"
    if not top.exists() or top.read_text() != text:   # keep mtime stable for Verilator
        top.write_text(text)
    return [top, *sources]


def c_header(cfg: SoCConfig) -> str:
    lines = [
        "/* Generated by `python -m rvgrid gen` from rvgrid/config.py. Do not edit. */",
        "#pragma once",
        "",
        f"#define SOC_CLK_HZ            {cfg.clk_hz}u",
        f"#define SOC_UART_DIVISOR      {cfg.divisor}u",
        "",
    ]
    for r in all_regions(cfg):
        lines.append(f"/* {r.name}: {r.desc} ({r.scope}) */")
        lines.append(f"#define {r.name + '_BASE':<22}0x{r.base:08X}u")
        lines.append(f"#define {r.name + '_SIZE':<22}0x{r.size:08X}u")
        for reg in getattr(r.periph, "REGS", ()):
            macro = f"{r.name}_{reg.name}"
            lines.append(f"#define {macro:<22}(*(volatile unsigned int *)0x{r.base + reg.offset:08X}u)"
                         f"  /* {reg.access}: {reg.desc} */")
        lines.append("")
    return "\n".join(lines)


def linker_memory(cfg: SoCConfig) -> str:
    l1 = next(r for r in all_regions(cfg) if r.name == "L1")
    return (
        "/* Generated by `python -m rvgrid gen` from rvgrid/config.py. Do not edit. */\n"
        "MEMORY\n{\n"
        f"    L1 (rwx) : ORIGIN = 0x{l1.base:08X}, LENGTH = 0x{l1.size:X}\n"
        "}\n"
    )


def generate_headers(cfg: SoCConfig, out_dir=BUILD / "include"):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {"soc.h": c_header(cfg), "memory.ld": linker_memory(cfg)}
    for fname, text in files.items():
        path = out_dir / fname
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    return [out_dir / f for f in files]
